-- SQL script to create database and insert sample data from the lab sheet.
IF DB_ID('QUANLYBANHANG') IS NULL
    CREATE DATABASE QUANLYBANHANG;
GO
USE QUANLYBANHANG;
GO

CREATE TABLE KHACHHANG (
    MAKH VARCHAR(10) PRIMARY KEY,
    TENKH NVARCHAR(30) NOT NULL,
    DIACHI NVARCHAR(50),
    DT VARCHAR(11),
    EMAIL VARCHAR(30)
);

CREATE TABLE VATTU (
    MAVT VARCHAR(10) PRIMARY KEY,
    TENVT NVARCHAR(30) NOT NULL,
    DVT NVARCHAR(20),
    GIAMUA MONEY CHECK (GIAMUA > 0),
    SLTON INT CHECK (SLTON >= 0)
);

CREATE TABLE HOADON (
    MAHD VARCHAR(10) PRIMARY KEY,
    NGAY DATE,
    MAKH VARCHAR(10),
    TONGTG FLOAT,
    FOREIGN KEY (MAKH) REFERENCES KHACHHANG(MAKH)
);

CREATE TABLE CTHD (
    MAHD VARCHAR(10),
    MAVT VARCHAR(10),
    SL INT CHECK (SL > 0),
    KHUYENMAI FLOAT,
    GIABAN FLOAT,
    PRIMARY KEY (MAHD, MAVT),
    FOREIGN KEY (MAHD) REFERENCES HOADON(MAHD),
    FOREIGN KEY (MAVT) REFERENCES VATTU(MAVT)
);

